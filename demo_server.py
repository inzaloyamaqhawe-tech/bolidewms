"""
Bolide Tanzania Warehouse & Production Management System - DEMO BACKEND
=====================================================================
A self-contained, dependency-light Flask server that serves DEMO data to
public/index.html (a rebranded copy of the DSA Warehouse frontend,
repointed at this server). Same underlying MOs/materials/workflows as the
original wms-dsa demo build - only the branding (logo, colors, name) and
this file changed.

This is NOT a real backend for any production system and never touches a
real database. Everything here lives in demo_data.json, generated by
generate_demo_data.py, and is mutated in-memory + persisted to disk so
picking materials, submitting reissue requests, approving them, adding
comments, etc. all "stick" between page reloads - exactly like the real
system, just backed by fixtures instead of SQL Server.

Run locally:
    pip install -r requirements.txt
    python demo_server.py
Then open http://127.0.0.1:5057/ in a browser - this server serves BOTH the
API and the frontend (public/index.html) on the same origin, so there's
nothing else to start.

Deploy (e.g. Render "Web Service"):
    Build command:  pip install -r requirements.txt
    Start command:  gunicorn demo_server:app
    (see render.yaml for a ready-made blueprint)

Logins:
    LANGA / DSA100%   -> Warehouse Admin   (role: admin)
    SIZWE / DSA200%   -> DSA Production    (role: dsaprod)
    SAM   / DSA300%   -> Management        (role: management)
    DANI  / DSA400%   -> Warehouse User    (role: warehouse)
"""
