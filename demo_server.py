@app.route("/mo_workstation_latest", methods=["GET"])
def get_mo_workstation_latest():
    mo_numbers = {m.strip().upper() for m in (request.args.get("mo_numbers", "")).split(",") if m.strip()}
    latest = {}
    for r in WORKSTATION_HISTORY:
        mo = r["mo_number"].upper()
        if mo_numbers and mo not in mo_numbers:
            continue
        prev = latest.get(mo)
        if not prev or r["changed_at"] > prev["changed_at"]:
            latest[mo] = r
    return jsonify(list(latest.values())), 200


