@app.route("/mo_material/update_qty_issued", methods=["POST"])
def update_qty_issued():
    data = request.get_json(force=True, silent=True) or {}
    moh_id = data.get("moh_id")
    items = data.get("items", [])
    mo = find_mo_by_moh(moh_id)
    if not mo or not items:
        return jsonify({"error": "moh_id and items are required"}), 400

    with LOCK:
        updated = 0
        touched_items = set()
        for item in items:
            item_number = item.get("item_number")
            qty_picked = float(item.get("qty_picked", 0) or 0)
            mode = item.get("mode", "normal")
            if not item_number or qty_picked <= 0:
                continue
            line = next((l for l in DB["mo_material"]
                        if l["moh_id"] == moh_id and l["item_number"] == item_number), None)
            if not line:
                continue
            if mode == "reissue":
                line["Qty_Scrap"] = round(line["Qty_Scrap"] + qty_picked, 2)
                line["qty_scrap"] = line["Qty_Scrap"]
            else:
                line["Qty_Issued"] = round(line["Qty_Issued"] + qty_picked, 2)
                line["qty_issued"] = line["Qty_Issued"]
                line["Status_id"] = 86 if line["Qty_Issued"] >= line["Qty_Required"] else 145
            # Decrement bulk warehouse stock
            for w in DB["whmoitems"]:
                if w["item_number"] == item_number:
                    w["total_stock"] = max(0.0, round(w["total_stock"] - qty_picked, 2))
                    w["stock_on_hand"] = w["total_stock"]
                    w["updated_at"] = now_iso()
            # Log to reports / bulk issue history
            DB["reports"].append({
                "id": next_id("report_id"), "action": "reissue" if mode == "reissue" else "issue",
                "mo": mo["mo_number"], "item": item_number, "qty": qty_picked,
                "batch_no": f"B{next_id('report_id') + 9000}", "mode": mode,
                "issued_by": data.get("issued_by", "DANI"),
                "time": now_iso(), "notes": None, "items": None, "created_at": now_iso(),
            })
            touched_items.add(item_number)
            updated += 1

        # Recompute header-level Qty_Issued + status
        mo_lines = [l for l in DB["mo_material"] if l["moh_id"] == moh_id]
        total_required = sum(l["Qty_Required"] for l in mo_lines)
        total_issued = sum(l["Qty_Issued"] for l in mo_lines)
        mo["Qty_Issued"] = round(total_issued, 1)
        if mo.get("Status") in ("New MO",):
            mo["Status"] = "Started"
            mo["status"] = "Started"
        if total_required > 0 and total_issued >= total_required:
            mo["Status"] = "Issued"
            mo["status"] = "Issued"
            mo["Status_ID"] = 86
            mo["status_id"] = 86
        for item_number in touched_items:
            recompute_whmoitem(item_number)
        save_db()

    return jsonify({"status": "ok", "updated": updated}), 200


