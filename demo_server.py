@app.route("/mo_assignments/create", methods=["POST"])
def create_mo_assignment():
    data = request.get_json(force=True, silent=True) or {}
    mo_number = data.get("mo_number")
    moh_id = data.get("moh_ID") or data.get("moh_id")
    if not mo_number or not moh_id:
        return jsonify({"error": "mo_number and moh_ID are required"}), 400
    with LOCK:
        specific_users = data.get("production_user_id")
        if isinstance(specific_users, str):
            try:
                specific_users = json.loads(specific_users)
            except Exception:
                specific_users = []
        specific_users = specific_users or []
        if specific_users:
            for su in specific_users:
                uid = su.get("user_id") or su.get("production_user_id")
                pu = next((p for p in DB["production_users"] if p["id"] == uid), None)
                ws = next((w for w in DB["workstations"] if w["id"] == su.get("workstation_id")), None)
                existing = next((a for a in DB["mo_assignments"]
                                 if a["mo_number"] == mo_number and a["production_user_id"] == uid), None)
                payload = {
                    "mo_number": mo_number, "moh_ID": moh_id,
                    "employee_username": pu["employee_username"] if pu else su.get("employee_username"),
                    "user_name": pu["full_name"] if pu else su.get("name"),
                    "workstation": ws["name"] if ws else su.get("workstation_name"),
                    "workstation_id": ws["id"] if ws else su.get("workstation_id"),
                    "production_user_id": uid, "assigned_by": data.get("assigned_by", "unknown"),
                    "assigned_at": now_iso(), "is_priority": data.get("is_priority", 0),
                    "notes": data.get("notes"), "workstations": None,
                }
                if existing:
                    existing.update(payload)
                else:
                    payload["id"] = next_id("assignment_id")
                    DB["mo_assignments"].append(payload)
        else:
            DB["mo_assignments"].append({
                "id": next_id("assignment_id"), "mo_number": mo_number, "moh_ID": moh_id,
                "employee_username": None, "user_name": None, "workstation": None, "workstation_id": None,
                "production_user_id": None, "assigned_by": data.get("assigned_by", "unknown"),
                "assigned_at": now_iso(), "is_priority": data.get("is_priority", 0),
                "notes": data.get("notes"), "workstations": data.get("workstations", []),
            })
        save_db()
    return jsonify({"status": "ok"}), 200


