def recompute_whmoitem(item_number):
    """Recalculate required_qty/shortage for a bulk stock item from live MO material lines."""
    outstanding = 0.0
    for line in DB["mo_material"]:
        if line["item_number"] == item_number:
            mo = find_mo_by_moh(line["moh_id"])
            if mo and mo.get("Status") in ("Transferred", "Completed", "Closed"):
                continue
            outstanding += max(0.0, line["Qty_Required"] - line["Qty_Issued"])
    for w in DB["whmoitems"]:
        if w["item_number"] == item_number:
            w["required_qty"] = round(outstanding, 1)
            w["required_qty_db"] = w["required_qty"]
            w["shortage"] = max(0.0, round(outstanding - w["total_stock"], 1))
            w["short"] = w["shortage"]
            w["updated_at"] = now_iso()


