def load_db():
    path = STATE_PATH if os.path.exists(STATE_PATH) else SEED_PATH
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


DB = load_db()


def build_workstation_history():
    """Derive MOTrack.dbo.mo_workstation_history-shaped rows (who is/was at which
    workstation right now) from the workstation_completions production-tally
    table. These are two different real tables upstream; the completions table
    only carries qty in/out, while history carries the human-readable
    workstation name + employee_username the Assigned MOs screen renders."""
    rows = []
    for i, c in enumerate(DB["workstation_completions"]):
        rows.append({
            "id": i + 1,
            "mo_number": c["mo_number"],
            "workstation": c["workstation_name"],
            "workstation_id": c["workstation_id"],
            "employee_username": c["created_by"],
            "previous_workstation": None,
            "previous_workstation_id": None,
            "changed_at": c["started_at"],
            "notes": None,
            "change_type": "assigned",
        })
    return rows


WORKSTATION_HISTORY = build_workstation_history()


def save_db():
    with open(STATE_PATH, "w", encoding="utf-8") as f:
        json.dump(DB, f, indent=2)


