@app.route("/reissue_requests/create", methods=["POST"])
def create_reissue_request():
    data = request.get_json(force=True, silent=True) or {}
    mo_number = data.get("mo_number")
    moh_id = data.get("moh_ID") or data.get("moh_id")
    requested_by = data.get("requested_by")
    reason = data.get("reason")
    items = data.get("items", [])
    if not all([mo_number, moh_id, requested_by, reason, items]):
        return jsonify({"error": "Missing required fields"}), 400
    u = find_user(requested_by) or {}
    with LOCK:
        entry = {
            "id": next_id("reissue_id"), "mo_number": mo_number, "moh_ID": moh_id,
            "requested_by": requested_by,
            "requested_by_name": f"{u.get('name','')} {u.get('surname','')}".strip() or requested_by,
            "reason": reason, "items": items, "status": data.get("status", "pending"),
            "requested_at": now_iso(), "reviewed_by": None, "reviewed_by_name": None,
            "reviewed_at": None, "admin_response": None,
        }
        DB["reissue_requests"].append(entry)
        save_db()
    return jsonify({"status": "ok"}), 200


